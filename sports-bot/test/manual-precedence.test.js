import test from 'node:test';
import assert from 'node:assert/strict';
import { predictGame } from '../src/predictionEngine.js';

const now = Date.now(), updatedAt = new Date(now - 600_000).toISOString();
const away = { name: 'Road Club', league: 'NBA', powerRating: 50, offense: 50, defense: 50, form: 50, autoGenerated: true, updatedAt };
const home = { ...away, name: 'Home Club' };
const game = { id: 'current-game', dateKey: new Date(now).toISOString().slice(0, 10), league: 'NBA', leagueKey: 'nba', sportGroup: 'Basketball',
  statusKey: 'scheduled', startTime: new Date(now + 3_600_000).toISOString(),
  away: { name: away.name, record: '10-10' }, home: { name: home.name, record: '10-10' },
  autoTeamMetrics: { away, home } };
function predict(overrides = {}, customGame = game) {
  return predictGame(customGame, 0, { now, intelligence: { teams: { away, home, ...(overrides.teams || {}) },
    players: overrides.players || {}, contexts: overrides.contexts || {} },
    history: { overall: { sampleSize: 0 } }, calibration: {}, featureLearning: {}, drift: {}, eloRatings: {} });
}

test('older or future manual team rows cannot replace fresher automatic ratings', () => {
  const baseline = predict();
  for (const stamp of [new Date(now - 86_400_000).toISOString(), new Date(now + 1000).toISOString(), 'invalid']) {
    const result = predict({ teams: { home: { ...home, autoGenerated: false, updatedAt: stamp, powerRating: 100 } } });
    assert.deepEqual(result.outcomeProbabilities, baseline.outcomeProbabilities);
  }
  const fresh = predict({ teams: { home: { ...home, autoGenerated: false, updatedAt: new Date(now - 1000).toISOString(), powerRating: 100 } } });
  assert.notDeepEqual(fresh.outcomeProbabilities, baseline.outcomeProbabilities);
});

test('old manual player status cannot overwrite a newer automatic injury/availability row', () => {
  const player = { team: home.name, name: 'Player One', league: 'NBA', autoGenerated: true, role: 'Point Guard', impact: 9,
    availability: 100, status: 'available', updatedAt };
  const customGame = { ...game, autoPlayers: [player] };
  const baseline = predict({}, customGame);
  const result = predict({ players: { one: { ...player, autoGenerated: false, availability: 0, status: 'out',
    updatedAt: new Date(now - 86_400_000).toISOString() } } }, customGame);
  assert.deepEqual(result.outcomeProbabilities, baseline.outcomeProbabilities);
});

test('manual context for another event or invalid expiry cannot leak into the current matchup', () => {
  const baseline = predict();
  const context = { gameId: 'other-game', league: 'NBA', dateKey: game.dateKey,
    awayTeam: away.name, homeTeam: home.name, updatedAt, factors: { homeRestDays: 6, awayRestDays: 0 } };
  assert.deepEqual(predict({ contexts: { one: context } }).outcomeProbabilities, baseline.outcomeProbabilities);
  assert.deepEqual(predict({ contexts: { one: { ...context, gameId: game.id, expiresAt: 'invalid' } } }).outcomeProbabilities,
    baseline.outcomeProbabilities);
});
