import test from 'node:test';
import assert from 'node:assert/strict';
import {buildSportModelPrediction} from '../src/sportModels.js';
import {predictGame} from '../src/predictionEngine.js';
import {recordPredictionJournal,readPredictionJournal} from '../src/predictionJournal.js';
const now=Date.parse('2099-02-01T18:00:00Z'),updatedAt='2099-02-01T17:59:00Z';
const game=(change={})=>({id:'health-fixture',leagueKey:'nhl',league:'NHL',sportGroup:'Hockey',statusKey:'scheduled',startTime:'2099-02-01T20:00:00Z',away:{name:'Away Club',abbr:'AWY'},home:{name:'Home Club',abbr:'HOM'},autoPlayers:[],...change});
const player=(change={})=>({id:'p1',athleteId:'1',name:'Goalie A',team:'Away Club',role:'Goalie',availability:100,status:'Available',autoGenerated:true,updatedAt,...change});
const model=(rows=[],change={})=>buildSportModelPrediction(game({...change,autoPlayers:rows}),{modelLogit:0,now});
const awayRole=result=>result.availabilityEvidence.roles.find(row=>row.side==='away'&&row.role==='goalie');
test('unobserved role-prior health cannot move the specialist away from its missing-role baseline',()=>{
 const prior=player({availability:100,status:'probable starter',availabilityEvidence:'role_prior_not_injury_clearance',starter:true});
 assert.deepEqual(model([prior]).probabilities,model().probabilities);assert.equal(awayRole(model([prior])).unknownPlayers,1);assert.equal(awayRole(model([prior])).observedPlayers,0);
});
test('current Out and inactive assertions veto contradictory full-workload projections',()=>{
 const projection={expectedShare:1,historicalShare:1,availabilityProbability:1};
 const healthy=model([player({participationProjection:projection})]);
 for(const change of [{status:'Out',availability:null},{active:false},{availability:0}]){
  const out=model([player({...change,participationProjection:projection})]);assert.ok(out.expectedScores.home>healthy.expectedScores.home);assert.equal(awayRole(out).value,-.55);
 }
});
test('a current partial availability assertion caps a stale full-workload projection',()=>{
 const p=player({status:'Questionable',availability:52,participationProjection:{expectedShare:1,historicalShare:1}});assert.ok(awayRole(model([p])).value<0);
});
test('equivalent fraction and percentage health values produce the same specialist adjustment',()=>{
 assert.deepEqual(model([player({availability:1})]).probabilities,model([player({availability:100})]).probabilities);
 assert.deepEqual(model([player({availability:.52,status:'unknown'})]).probabilities,model([player({availability:52,status:'unknown'})]).probabilities);
});
test('invalid workload numbers cannot invent a missing-workload penalty',()=>{
 const clean=model([player()]);for(const projection of [{expectedShare:true,historicalShare:1},{expectedShare:null,historicalShare:1},{expectedShare:1,historicalShare:0}])assert.deepEqual(model([player({participationProjection:projection})]).probabilities,clean.probabilities);
});
test('same-player contradictions are conservative and independent of row order',()=>{
 const healthy=player(),out=player({status:'Out',availability:0});const one=model([healthy,out]),two=model([out,healthy]);assert.deepEqual(one.probabilities,two.probabilities);assert.equal(awayRole(one).observedPlayers,1);assert.equal(awayRole(one).value,-.55);
});
test('side hints cannot transfer a known opponent player and abbreviations match the correct side',()=>{
 const wrong=player({team:'Home Club',side:'away'});assert.deepEqual(model([wrong]).probabilities,model().probabilities);assert.ok(model([wrong]).availabilityEvidence.exclusions.team_side_conflict);
 assert.notDeepEqual(model([player({team:'AWY'})]).probabilities,model().probabilities);
});
test('future and expired player assertions cannot supply specialist health at an earlier cutoff',()=>{
 for(const patch of [{updatedAt:'2099-02-01T18:01:00Z'},{availabilityExpiresAt:'2099-02-01T17:59:59Z'},{updatedAt:'2099-02-30T17:59:00Z'}])assert.deepEqual(model([player(patch)]).probabilities,model().probabilities);
});
test('specialist receives the same selected newer manual player status as primary inference',()=>{
 const g=game({autoPlayers:[player()]}),manual=player({autoGenerated:false,status:'Out',availability:0,updatedAt:'2099-02-01T17:59:30Z'}),original=structuredClone(g);
 const prediction=predictGame(g,1,{now,intelligence:{players:{manual}}});assert.equal(awayRole(prediction.sportModel).value,-.55);assert.deepEqual(g,original);
});
test('an older or future manual override cannot replace the automatic specialist input',()=>{
 const g=game({autoPlayers:[player()]});for(const stamp of ['2099-02-01T17:00:00Z','2099-02-01T18:01:00Z']){
  const p=predictGame(g,1,{now,intelligence:{players:{one:player({autoGenerated:false,status:'Out',availability:0,updatedAt:stamp})}}});assert.ok(Math.abs(awayRole(p.sportModel).value-.45)<1e-12);
 }
});
test('missing specialist role evidence is visible in the frozen forecast journal',async()=>{
 const g=game(),p=predictGame(g,1,{now}),slate={guildId:'specialist-health',dateKey:'2099-02-01',generatedAt:new Date(now).toISOString(),games:[g],predictions:[p]};
 assert.equal(p.evidenceCoverage.specialistAvailability.roles.length,2);assert.equal(p.sportModel.availabilityEvidence.missingRoles.length,2);
 await recordPredictionJournal(slate,{now});const rows=await readPredictionJournal();const row=rows.find(row=>row.type==='forecast'&&row.payload.gameId===g.id);assert.ok(row);assert.equal(row.payload.evidenceCoverage.specialistAvailability.missingRoles.length,2);
});
test('explicit role restrictions affect the expected side in each existing sport equation',()=>{
 for(const [leagueKey,sportGroup,role] of [['nfl','Football','Quarterback'],['mlb','Baseball','Starting Pitcher'],['nhl','Hockey','Goalie'],['epl','Soccer','Goalkeeper']]){
  const context={leagueKey,sportGroup},healthy=model([player({role})],context),out=model([player({role,status:'Out',availability:null})],context);
  assert.ok(out.probabilities.home>healthy.probabilities.home,leagueKey);
 }
});
test('the same identified player cannot be counted again through a team abbreviation',()=>{
 const one=player(),alias=player({team:'AWY'}),other=player({athleteId:'2',name:'Goalie B',status:'Out',availability:0});
 const a=model([one,other]),b=model([one,alias,other]);assert.deepEqual(a.probabilities,b.probabilities);assert.equal(awayRole(b).observedPlayers,2);
});
test('a later nested workload observation cannot influence an earlier specialist forecast',()=>{
 const one=player({participationProjection:{fetchedAt:'2099-02-01T18:01:00Z',expectedShare:0,historicalShare:1}});assert.deepEqual(model([one]).probabilities,model([player()]).probabilities);assert.ok(awayRole(model([one])).exclusions.projection_after_information_cutoff);
});
test('an explicitly invalid specialist cutoff cannot silently use wall-clock time',()=>{
 assert.throws(()=>buildSportModelPrediction(game(),{now:NaN}),/cutoff/);
});
