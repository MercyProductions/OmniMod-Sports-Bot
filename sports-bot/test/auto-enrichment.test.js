function event(id, date, awayScore, homeScore, completed = true) {
  return {
    id,
    date,
    status: { type: { completed } },
    competitions: [{
      id,
      date,
      status: { type: { completed } },
      competitors: [
        { homeAway: 'away', score: String(awayScore), team: { id: '1', displayName: 'Away Team', abbreviation: 'AWY' } },
        { homeAway: 'home', score: String(homeScore), team: { id: '2', displayName: 'Home Team', abbreviation: 'HOM' } }
      ]
    }]
  };
}

function game(overrides = {}) {
  return {
    id: '401000001', league: 'NBA', leagueKey: 'nba', sportGroup: 'Basketball', matchup: 'AWY @ HOM',
    startTime: '2099-02-01T19:00:00Z', dateKey: '2099-02-01', statusKey: 'scheduled', statusLabel: 'Upcoming',
    source: 'ESPN public scoreboard', sourceMeta: { provider: 'ESPN', cacheState: 'network', fetchedAt: new Date().toISOString() },
    away: { name: 'Away Team', abbr: 'AWY', record: '', score: 0 },
    home: { name: 'Home Team', abbr: 'HOM', record: '', score: 0 },
    odds: null,
    ...overrides
  };
}

test('automatic history parser accepts only completed games before prediction day', () => {
  const oldFinal = event('old-final', '2099-01-30T20:00:00Z', 90, 110);
  oldFinal.competitions[0].competitors[0].probables = [{
    playerId: 'pitcher-1', athlete: { id: 'pitcher-1', displayName: 'Road Ace', position: 'SP' }, displayName: 'Probable Starting Pitcher'
  }];
  const rows = parseEspnHistoryEvents({ events: [
    oldFinal,
    event('same-day', '2099-02-01T20:00:00Z', 95, 105),
    event('not-final', '2099-01-31T20:00:00Z', 0, 0, false)
  ] }, league, '2099-02-01', { fetchedAt: '2099-02-01T12:00:00Z', cacheState: 'stale', truncated: true });
  assert.equal(rows.length, 1);
  assert.equal(rows[0].id, 'espn:old-final');
  assert.equal(rows[0].homeScore, 110);
  assert.equal(rows[0].sourceMeta.cacheState, 'stale');
  assert.equal(rows[0].sourceMeta.truncated, true);
  assert.equal(rows[0].probableStarters[0].name, 'Road Ace');
});

test('automatic team profiles derive shrunk power, form, offense, defense, and rest', () => {
  const results = Array.from({ length: 12 }, (_, index) => ({
    id: `r-${index}`,
    dateKey: `2099-01-${String(index + 1).padStart(2, '0')}`,
    startTime: `2099-01-${String(index + 1).padStart(2, '0')}T20:00:00Z`,
    league: 'NBA', leagueKey: 'nba', sportGroup: 'Basketball',
    awayTeam: 'Away Team', awayAbbr: 'AWY', homeTeam: 'Home Team', homeAbbr: 'HOM',
    awayScore: 90 + (index % 3), homeScore: 108 + (index % 4)
  }));
  const profiles = Object.values(buildAutomaticTeamProfiles(results, new Date('2099-02-01T12:00:00Z'), '2099-02-01T00:00:00Z'));
  const away = profiles.find((row) => row.name === 'Away Team');
  const home = profiles.find((row) => row.name === 'Home Team');
  assert.equal(home.sampleSize, 12);
  assert.ok(home.powerRating > away.powerRating);
  assert.ok(home.offense > away.offense);
  assert.ok(home.defense > away.defense);
  assert.ok(home.form > away.form);
  assert.ok(Number.isFinite(home.restDays));
  assert.equal(home.autoGenerated, true);
});

