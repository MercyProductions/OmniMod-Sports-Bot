test('automatic injuries affect predictions without masquerading as local data', () => {
  const intelligence = {
    teams: {
      away: { name: 'Away Team', leagueKey: 'nba', powerRating: 50, offense: 50, defense: 50, form: 50, autoGenerated: true },
      home: { name: 'Home Team', leagueKey: 'nba', powerRating: 50, offense: 50, defense: 50, form: 50, autoGenerated: true }
    },
    players: {}, contexts: {}, results: {}
  };
  const modelContext = { intelligence, history: { overall: { sampleSize: 0 } }, calibration: {}, eloRatings: {}, externalResults: [] };
  const healthy = predictGame(game(), 0, modelContext);
  const injured = predictGame(game({ autoPlayers: [{
    id: 'auto-99', name: 'Home Star', team: 'Home Team', league: 'NBA', role: 'Point Guard',
    impact: 7, availability: 0, status: 'Out', starter: true, form: 50, autoGenerated: true, updatedAt: new Date().toISOString()
  }] }), 0, modelContext);
  assert.ok(injured.outcomeProbabilities.home < healthy.outcomeProbabilities.home - 3);
  assert.equal(injured.localDataConfidenceValue, healthy.localDataConfidenceValue);
  assert.match(injured.signals.join(' '), /Home Star/);
});

test('automatic enrichment stays inside league/game request caps and reuses its cache', async () => {
  const originalFetch = globalThis.fetch;
  let calls = 0;
  const urls = [];
  globalThis.fetch = async (url) => {
    calls += 1;
    urls.push(String(url));
    const payload = String(url).includes('/summary?')
      ? { injuries: [], rosters: [], pickcenter: [] }
      : { events: [event('401000002', '2099-01-20T20:00:00Z', 91, 109)] };
    return new Response(JSON.stringify(payload), { status: 200, headers: { 'content-type': 'application/json' } });
  };
  try {
    const groupedLeague = { ...league, groups: '50' };
    const first = await enrichGamesAutomatically([game()], new Date('2099-02-01T12:00:00Z'), { leagues: [groupedLeague] });
    const second = await enrichGamesAutomatically([game()], new Date('2099-02-01T12:00:00Z'), { leagues: [groupedLeague] });
    assert.equal(first.externalCalls, 3);
    assert.equal(second.externalCalls, 0);
    assert.equal(calls, 3);
    assert.equal(first.historyLeagues, 1);
    assert.equal(first.summaryGames, 1);
    assert.equal(first.historyResults.length, 1);
    assert.equal(first.historicalBoxscores, 1);
    assert.ok(urls.some((url) => url.includes('limit=999') && url.includes('groups=50')));
  } finally {
    globalThis.fetch = originalFetch;
  }
});

test('daily slate integrates automatic history and event injuries without paid odds', async () => {
  const originalFetch = globalThis.fetch;
  globalThis.fetch = async (rawUrl) => {
    const url = new URL(rawUrl);
    if (url.pathname.endsWith('/summary')) {
      return new Response(JSON.stringify({
        rosters: [{ roster: [{ starter: true, athlete: { id: '99' } }] }],
        injuries: [{ team: { displayName: 'Home Team' }, injuries: [{
          status: 'Out', type: { description: 'Out' },
          athlete: { id: '99', displayName: 'Home Star', position: { displayName: 'Point Guard' } }
        }] }],
        pickcenter: []
      }), { status: 200, headers: { 'content-type': 'application/json' } });
    }
    if (url.searchParams.get('dates') === '20990201') {
      const scheduled = event('401000003', '2099-02-01T20:00:00Z', 0, 0, false);
      return new Response(JSON.stringify({ events: [scheduled] }), { status: 200, headers: { 'content-type': 'application/json' } });
    }
    return new Response(JSON.stringify({ events: [event('401000002', '2099-01-20T20:00:00Z', 91, 109)] }), { status: 200, headers: { 'content-type': 'application/json' } });
  };
  try {
    const slate = await buildDailySlate(new Date('2099-02-01T18:00:00Z'), {
      guildId: 'auto-integration', leagueKeys: ['nba'], includeOdds: false
    });
    assert.equal(slate.games.length, 1);
    assert.equal(slate.modelSummary.automatic.historyFinals, 1);
    assert.equal(slate.modelSummary.automatic.teamProfiles, 2);
    assert.equal(slate.modelSummary.automatic.injuryRecords, 1);
    assert.ok(slate.predictions[0].apiConfidenceValue > 0);
    assert.match(slate.predictions[0].signals.join(' '), /Home Star/);
    assert.match(slate.source, /history\/box scores\/lineups/);
  } finally {
    globalThis.fetch = originalFetch;
  }
});


