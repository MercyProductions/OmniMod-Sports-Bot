const league = { key: 'nba', sport: 'basketball', league: 'nba', label: 'NBA', group: 'Basketball', priority: 100 };

function event(id, date, awayScore, homeScore, completed = true) {
  return {
    id,
    date,
    status: { type: { completed } },
    competitions: [{
      id,
      date,
      status: { type: { completed } },
      competitors: [
        { homeAway: 'away', score: String(awayScore), team: { id: '1', displayName: 'Away Team', abbreviation: 'AWY' } },
        { homeAway: 'home', score: String(homeScore), team: { id: '2', displayName: 'Home Team', abbreviation: 'HOM' } }
      ]
    }]
  };
}

function game(overrides = {}) {
  return {
    id: 'future-game', league: 'NBA', leagueKey: 'nba', sportGroup: 'Basketball', matchup: 'AWY @ HOM',
    startTime: '2099-02-01T19:00:00Z', dateKey: '2099-02-01', statusKey: 'scheduled', statusLabel: 'Upcoming',
    source: 'ESPN public scoreboard', sourceMeta: { provider: 'ESPN', cacheState: 'network', fetchedAt: new Date().toISOString() },
    away: { name: 'Away Team', abbr: 'AWY', record: '', score: 0 },
    home: { name: 'Home Team', abbr: 'HOM', record: '', score: 0 },
    odds: null,
    ...overrides
  };
}

test('automatic history parser accepts only completed games before prediction day', () => {
  const oldFinal = event('old-final', '2099-01-30T20:00:00Z', 90, 110);
  oldFinal.competitions[0].competitors[0].probables = [{
    playerId: 'pitcher-1', athlete: { id: 'pitcher-1', displayName: 'Road Ace', position: 'SP' }, displayName: 'Probable Starting Pitcher'
  }];
  const rows = parseEspnHistoryEvents({ events: [
    oldFinal,
    event('same-day', '2099-02-01T20:00:00Z', 95, 105),
    event('not-final', '2099-01-31T20:00:00Z', 0, 0, false)
  ] }, league, '2099-02-01', { fetchedAt: '2099-02-01T12:00:00Z', cacheState: 'stale', truncated: true });
  assert.equal(rows.length, 1);
  assert.equal(rows[0].id, 'espn:old-final');
  assert.equal(rows[0].homeScore, 110);
  assert.equal(rows[0].sourceMeta.cacheState, 'stale');
  assert.equal(rows[0].sourceMeta.truncated, true);
  assert.equal(rows[0].probableStarters[0].name, 'Road Ace');
});

test('automatic team profiles derive shrunk power, form, offense, defense, and rest', () => {
  const results = Array.from({ length: 12 }, (_, index) => ({
    id: `r-${index}`,
    dateKey: `2099-01-${String(index + 1).padStart(2, '0')}`,
    startTime: `2099-01-${String(index + 1).padStart(2, '0')}T20:00:00Z`,
    league: 'NBA', leagueKey: 'nba', sportGroup: 'Basketball',
    awayTeam: 'Away Team', awayAbbr: 'AWY', homeTeam: 'Home Team', homeAbbr: 'HOM',
    awayScore: 90 + (index % 3), homeScore: 108 + (index % 4)
  }));
  const profiles = Object.values(buildAutomaticTeamProfiles(results, new Date('2099-02-01T12:00:00Z'), '2099-02-01T00:00:00Z'));
  const away = profiles.find((row) => row.name === 'Away Team');
  const home = profiles.find((row) => row.name === 'Home Team');
  assert.equal(home.sampleSize, 12);
  assert.ok(home.powerRating > away.powerRating);
  assert.ok(home.offense > away.offense);
  assert.ok(home.defense > away.defense);
  assert.ok(home.form > away.form);
  assert.ok(Number.isFinite(home.restDays));
  assert.equal(home.autoGenerated, true);
});

test('summary parser maps injuries and exposes only a de-vigged single-book fallback', () => {
  const parsed = parseEspnSummary({
    rosters: [{ roster: [{ starter: true, athlete: { id: '99' } }] }],
    injuries: [{
      team: { displayName: 'Home Team' },
      injuries: [{
        status: 'Out', athlete: { id: '99', displayName: 'Home Star', position: { displayName: 'Point Guard' } },
        type: { description: 'Out' }, details: { type: 'Ankle' }
      }]
    }],
    pickcenter: [{
      provider: { name: 'Example Book' }, spread: -3.5, overUnder: 218.5,
      awayTeamOdds: { moneyLine: 140 }, homeTeamOdds: { moneyLine: -165 }
    }]
  }, game(), { fetchedAt: '2099-02-01T12:00:00Z', cacheState: 'network' });
  assert.equal(parsed.players.length, 1);
  assert.equal(parsed.players[0].availability, 0);
  assert.equal(parsed.players[0].starter, true);
  assert.ok(parsed.players[0].impact > 2);
  assert.equal(parsed.odds.freeProvider, true);
  assert.equal(parsed.odds.bookmakerCount, 1);
  assert.ok(Math.abs(parsed.odds.h2h.away.fairProbability + parsed.odds.h2h.home.fairProbability - 1) < 1e-9);
});

test('automatic injuries affect predictions without masquerading as local data', () => {
  const intelligence = {
    teams: {
      away: { name: 'Away Team', leagueKey: 'nba', powerRating: 50, offense: 50, defense: 50, form: 50, autoGenerated: true },
      home: { name: 'Home Team', leagueKey: 'nba', powerRating: 50, offense: 50, defense: 50, form: 50, autoGenerated: true }
    },
    players: {}, contexts: {}, results: {}
  };
  const modelContext = { intelligence, history: { overall: { sampleSize: 0 } }, calibration: {}, eloRatings: {}, externalResults: [] };
  const healthy = predictGame(game(), 0, modelContext);
  const injured = predictGame(game({ autoPlayers: [{
    id: 'auto-99', name: 'Home Star', team: 'Home Team', league: 'NBA', role: 'Point Guard',
    impact: 7, availability: 0, status: 'Out', starter: true, form: 50, autoGenerated: true, updatedAt: new Date().toISOString()
  }] }), 0, modelContext);
  assert.ok(injured.outcomeProbabilities.home < healthy.outcomeProbabilities.home - 3);
  assert.equal(injured.localDataConfidenceValue, healthy.localDataConfidenceValue);
  assert.match(injured.signals.join(' '), /Home Star/);
});

test('automatic enrichment stays inside league/game request caps and reuses its cache', async () => {
  const originalFetch = globalThis.fetch;
  let calls = 0;
  const urls = [];
  globalThis.fetch = async (url) => {
    calls += 1;
    urls.push(String(url));
    const payload = String(url).includes('/summary?')
      ? { injuries: [], rosters: [], pickcenter: [] }
      : { events: [event('historical', '2099-01-20T20:00:00Z', 91, 109)] };
    return new Response(JSON.stringify(payload), { status: 200, headers: { 'content-type': 'application/json' } });
  };
  try {
    const groupedLeague = { ...league, groups: '50' };
    const first = await enrichGamesAutomatically([game()], new Date('2099-02-01T12:00:00Z'), { leagues: [groupedLeague] });
    const second = await enrichGamesAutomatically([game()], new Date('2099-02-01T12:00:00Z'), { leagues: [groupedLeague] });
    assert.equal(first.externalCalls, 3);
    assert.equal(second.externalCalls, 0);
    assert.equal(calls, 3);
    assert.equal(first.historyLeagues, 1);
    assert.equal(first.summaryGames, 1);
    assert.equal(first.historyResults.length, 1);
    assert.equal(first.historicalBoxscores, 1);
    assert.ok(urls.some((url) => url.includes('limit=999') && url.includes('groups=50')));
  } finally {
    globalThis.fetch = originalFetch;
  }
});

test('daily slate integrates automatic history and event injuries without paid odds', async () => {
  const originalFetch = globalThis.fetch;
  globalThis.fetch = async (rawUrl) => {
    const url = new URL(rawUrl);
    if (url.pathname.endsWith('/summary')) {
      return new Response(JSON.stringify({
        rosters: [{ roster: [{ starter: true, athlete: { id: '99' } }] }],
        injuries: [{ team: { displayName: 'Home Team' }, injuries: [{
          status: 'Out', type: { description: 'Out' },
          athlete: { id: '99', displayName: 'Home Star', position: { displayName: 'Point Guard' } }
        }] }],
        pickcenter: []
      }), { status: 200, headers: { 'content-type': 'application/json' } });
    }
    if (url.searchParams.get('dates') === '20990201') {
      const scheduled = event('slate-game', '2099-02-01T20:00:00Z', 0, 0, false);
      return new Response(JSON.stringify({ events: [scheduled] }), { status: 200, headers: { 'content-type': 'application/json' } });
    }
    return new Response(JSON.stringify({ events: [event('historical', '2099-01-20T20:00:00Z', 91, 109)] }), { status: 200, headers: { 'content-type': 'application/json' } });
  };
  try {
    const slate = await buildDailySlate(new Date('2099-02-01T18:00:00Z'), {
      guildId: 'auto-integration', leagueKeys: ['nba'], includeOdds: false
    });
    assert.equal(slate.games.length, 1);
    assert.equal(slate.modelSummary.automatic.historyFinals, 1);
    assert.equal(slate.modelSummary.automatic.teamProfiles, 2);
    assert.equal(slate.modelSummary.automatic.injuryRecords, 1);
    assert.ok(slate.predictions[0].apiConfidenceValue > 0);
    assert.match(slate.predictions[0].signals.join(' '), /Home Star/);
    assert.match(slate.source, /history\/box scores\/lineups/);
  } finally {
    globalThis.fetch = originalFetch;
  }
});
