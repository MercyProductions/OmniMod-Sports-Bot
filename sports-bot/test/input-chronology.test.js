import test from 'node:test';
import assert from 'node:assert/strict';
import {predictionInputsAt,observedInputState} from '../src/inputChronology.js';
import {predictGame} from '../src/predictionEngine.js';
const now=Date.parse('2026-01-01T18:00:00Z'),before=new Date(now-3600000).toISOString(),after=new Date(now+3600000).toISOString();
function game(){return {id:'cutoff-fixture',league:'NBA',leagueKey:'nba',sportGroup:'Basketball',statusKey:'scheduled',startTime:new Date(now+86400000).toISOString(),
 away:{name:'A',abbr:'A'},home:{name:'H',abbr:'H'},source:'ESPN public scoreboard',sourceMeta:{provider:'ESPN',fetchedAt:before,cacheState:'network'}};}

test('automatic future profiles cannot affect prediction probabilities at an earlier cutoff',()=>{
 const original=game(),baseline=predictGame(original,0,{now});
 const future=game();future.autoTeamMetrics={home:{name:'H',leagueKey:'nba',autoGenerated:true,updatedAt:after,powerRating:99,offense:99,defense:99}};
 future.autoPlayers=[{name:'Future Star',team:'H',leagueKey:'nba',autoGenerated:true,updatedAt:after,impact:10,availability:0}];
 const predicted=predictGame(future,0,{now});
 assert.deepEqual(predicted.outcomeProbabilities,baseline.outcomeProbabilities);
 assert.equal(predicted.inputChronology.excluded['auto_team_home:after_information_cutoff'],1);
 assert.equal(predicted.inputChronology.excluded['auto_player:after_information_cutoff'],1);
 assert.equal(future.autoPlayers.length,1);
});

test('summary/history dependencies are excluded together rather than keeping future derived lineups',()=>{
 const input=game();input.autoEnrichment={fetchedAt:after};input.autoPlayers=[{name:'derived'}];input.autoLineup={ratingDifference:50};input.autoContext={factors:{homeMotivation:100}};
 input.autoHistory={fetchedAt:before,fetchedAtBySide:{away:before,home:after}};input.autoTeamMetrics={home:{powerRating:100}};input.advancedDataset={homeXg:10};
 const filtered=predictionInputsAt(input,{},now);
 assert.equal(filtered.game.autoPlayers.length,0);assert.equal(filtered.game.autoLineup,null);assert.equal(filtered.game.advancedDataset,null);
 assert.deepEqual(filtered.game.autoTeamMetrics,{});assert.equal(input.autoLineup.ratingDifference,50);
 assert.equal(filtered.audit.excluded['autoHistory:after_information_cutoff'],1);
});

test('future quote timestamps cannot steer the model while contemporaneous prices can',()=>{
 const base=game(),h2h={lastUpdate:after,bookmakerCount:3,dispersion:0,away:{fairProbability:.2},home:{fairProbability:.8}};
 const unavailable=predictGame({...base,odds:{h2h}},0,{now});
 assert.equal(unavailable.marketBlendWeight,0);
 const available=predictGame({...base,odds:{h2h:{...h2h,lastUpdate:before}}},0,{now});
 assert.ok(available.marketBlendWeight>0);
 const nested=predictGame({...base,odds:{h2h:{...h2h,lastUpdate:before,home:{fairProbability:.8,quotes:[{lastUpdate:after}]}}}},0,{now});
 assert.equal(nested.marketBlendWeight,0);
 assert.equal(predictGame({...base,odds:{h2h:{...h2h,lastUpdate:false}}},0,{now}).marketBlendWeight,0);
});

test('freshness uses the supplied cutoff and future schedule records are not used',()=>{
 const context={now,intelligence:{teams:{home:{name:'H',leagueKey:'nba',updatedAt:before,powerRating:70},away:{name:'A',leagueKey:'nba',updatedAt:before,powerRating:50}}}};
 const prediction=predictGame(game(),0,context);
 assert.ok(prediction.localDataConfidenceValue>=39);
 const future=game();future.sourceMeta.fetchedAt=after;future.away.record='1-99';future.home.record='99-1';
 const filtered=predictionInputsAt(future,{},now);
 assert.equal(filtered.game.home.record,'');assert.equal(filtered.audit.excluded['schedule:after_information_cutoff'],1);
 assert.equal(predictGame(future,0,{now}).apiConfidenceValue,0);
 assert.throws(()=>predictGame(game(),0,{now:NaN}),/cutoff/);
});

test('later learning context and unknown head-to-head availability cannot become historical inputs',()=>{
 const result={startTime:before,dateKey:'2026-01-01',leagueKey:'nba',awayTeam:'A',homeTeam:'H',awayScore:1,homeScore:2};
 const filtered=predictionInputsAt(game(),{learningInputAudit:{cutoffAt:after},eloRatings:{some:2000},calibration:{all:[]},history:{overall:{sampleSize:100}},externalResults:[result]},now);
 assert.deepEqual(filtered.context.eloRatings,{});assert.equal(filtered.context.history.overall.sampleSize,0);
 assert.equal(filtered.context.externalResults.length,0);assert.equal(filtered.audit.excluded['head_to_head_result:availability_unknown'],1);
 assert.equal(filtered.audit.pointInTimeComplete,false);
});

test('unknown legacy availability remains disclosed and invalid or newer secondary timestamps fail closed',()=>{
 assert.equal(observedInputState({},now),'unknown');
 assert.equal(observedInputState({updatedAt:before,sourceFetchedAt:after},now),'after_information_cutoff');
 assert.equal(observedInputState({updatedAt:'invalid'},now),'invalid_observation_time');
 const filtered=predictionInputsAt(game(),{intelligence:{teams:{legacy:{name:'H',powerRating:70}}}},now);
 assert.ok(filtered.context.intelligence.teams.legacy);assert.equal(filtered.audit.unknownAvailability.manual_teams,1);
});
