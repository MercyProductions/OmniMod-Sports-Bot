test('automatic external results update Elo and bounded recent head-to-head', () => {
  const externalResults = Array.from({ length: 6 }, (_, index) => ({
    id: `external-${index}`, dateKey: `2098-12-${String(index + 1).padStart(2, '0')}`,
    startTime: `2098-12-${String(index + 1).padStart(2, '0')}T20:00:00Z`,
    observedAt:`2098-12-${String(index+1).padStart(2,'0')}T23:00:00Z`,
    league: 'NBA', leagueKey: 'nba', sportGroup: 'Basketball',
    awayTeam: 'Away Team', homeTeam: 'Home Team', awayScore: 90, homeScore: 110
  }));
  const ratings = buildEloRatings({ teams: {}, results: {} }, [], externalResults);
  assert.ok(lookupElo(ratings, 'nba', 'Home Team') > 1500);

  const baselineContext = {...context(),now:Date.parse('2099-01-01T12:00:00Z')};
  const baseline = predictGame(game(), 0, baselineContext);
  const enriched = predictGame(game(), 0, { ...baselineContext, externalResults });
  assert.ok(enriched.outcomeProbabilities.home > baseline.outcomeProbabilities.home);
  assert.match(enriched.signals.join(' '), /Recent head-to-head/);
});

test('official corroboration raises API confidence while a source conflict lowers it', () => {
  const base = game({
    source: 'ESPN public scoreboard',
    sourceMeta: { provider: 'ESPN', fetchedAt: new Date().toISOString(), cacheState: 'fresh' },
    autoHistory: { awayGames: 20, homeGames: 20, cacheState: 'fresh' },
    autoEnrichment: { injuryGroupsPresent: true, rosterGroups: 2, cacheState: 'fresh' }
  });
  const espnOnly = predictGame(base, 0, context());
  const corroborated = predictGame({
    ...base,
    sourceCorroboration: { providers: ['MLB StatsAPI'], matches: [{ provider: 'MLB StatsAPI' }], conflicts: [] }
  }, 0, context());
  const conflicted = predictGame({
    ...base,
    sourceCorroboration: { providers: ['MLB StatsAPI'], matches: [], conflicts: [{ provider: 'MLB StatsAPI' }] }
  }, 0, context());
  assert.ok(corroborated.apiConfidenceValue > espnOnly.apiConfidenceValue);
  assert.ok(conflicted.apiConfidenceValue < espnOnly.apiConfidenceValue);
  assert.ok(corroborated.apiConfidenceValue <= 96);
});

test('accepted sport learning changes only the validated feature multiplier', () => {
  const baseContext = context();
  baseContext.eloRatings = { nba__awayteam: 1400, nba__hometeam: 1600 };
  const baseline = predictGame(game(), 0, baseContext);
  const learned = predictGame(game(), 0, {
    ...baseContext,
    featureLearning: {
      basketball: {
        accepted: true, sampleSize: 120, brierImprovement: 0.012,
        weights: { 'Elo strength': 1.4 }
      }
    }
  });
  const learnedElo = learned.factors.find((row) => row.label === 'Elo strength');
  assert.equal(learnedElo.learnedMultiplier, 1.4);
  assert.ok(learned.outcomeProbabilities.home > baseline.outcomeProbabilities.home);
  assert.match(learned.signals.join(' '), /accepted Brier improvement/);
});

test('degraded sport drift shrinks confidence and blocks the lowest risk tier', () => {
  const strongContext = context();
  strongContext.intelligence.teams.home.powerRating = 90;
  strongContext.intelligence.teams.home.offense = 90;
  strongContext.intelligence.teams.home.defense = 90;
  strongContext.intelligence.teams.home.form = 90;
  strongContext.intelligence.teams.away.powerRating = 25;
  strongContext.intelligence.teams.away.offense = 25;
  strongContext.intelligence.teams.away.defense = 25;
  strongContext.intelligence.teams.away.form = 25;
  const stable = predictGame(game(), 0, strongContext);
  const degraded = predictGame(game(), 0, {
    ...strongContext,
    drift: { basketball: { status: 'degraded', penalty: 0.3 } }
  });
  assert.ok(degraded.confidenceValue < stable.confidenceValue);
  assert.notEqual(degraded.riskTier, 'Lower');
  assert.equal(degraded.driftPenalty, 30);
});

test('short rest for an automatically matched starting pitcher affects the baseball matchup', () => {
  const baseball = game({ league: 'MLB', leagueKey: 'mlb', sportGroup: 'Baseball' });
  const baseline = predictGame(baseball, 0, context());
  const shortRestAway = predictGame({
    ...baseball,
    autoContext: {
      autoGenerated: true,
      factors: { awayStarterRestDays: 2, homeStarterRestDays: 5 }
    }
  }, 0, context());
  assert.ok(shortRestAway.outcomeProbabilities.home > baseline.outcomeProbabilities.home);
  assert.match(shortRestAway.factors.find((row) => row.label === 'Situation/context').detail, /Starter rest 2 away vs 5 home/);
});
