import assert from 'node:assert/strict';
import test from 'node:test';
import { predictGame } from '../src/predictionEngine.js';
import {
  buildCalibrationModel,
  buildEloRatings,
  collectFeatureRows,
  collectGradedRows,
  evaluatePredictionRows,
  lookupElo
} from '../src/modelEvaluation.js';

function game(overrides = {}) {
  return {
    id: 'nba-example-1',
    league: 'NBA',
    leagueKey: 'nba',
    sportGroup: 'Basketball',
    matchup: 'AWY @ HOM',
    startTime: '2099-01-02T19:00:00-06:00',
    startTimeLocal: '7:00 PM',
    statusKey: 'scheduled',
    statusLabel: 'Upcoming',
    neutralSite: false,
    source: 'Manual local schedule',
    sourceMeta: { provider: 'local', cacheState: 'local' },
    away: { name: 'Away Team', abbr: 'AWY', record: '20-20', score: 0, winner: false },
    home: { name: 'Home Team', abbr: 'HOM', record: '20-20', score: 0, winner: false },
    odds: null,
    ...overrides
  };
}

function context(players = {}) {
  return {
    intelligence: {
      teams: {
        away: { id: 'away', name: 'Away Team', league: 'NBA', powerRating: 60, offense: 60, defense: 60, form: 50, updatedAt: new Date().toISOString() },
        home: { id: 'home', name: 'Home Team', league: 'NBA', powerRating: 60, offense: 60, defense: 60, form: 50, updatedAt: new Date().toISOString() }
      },
      players,
      contexts: {}, games: {}, results: {}
    },
    history: { overall: { sampleSize: 0 } },
    calibration: {},
    eloRatings: {}
  };
}

test('prediction confidence is a normalized outcome probability and is separate from API confidence', () => {
  const prediction = predictGame(game(), 0, context());
  const total = Object.values(prediction.outcomeProbabilities).reduce((sum, value) => sum + value, 0);
  assert.ok(Math.abs(total - 100) <= 0.2);
  assert.equal(prediction.apiConfidenceValue, 0);
  assert.ok(prediction.localDataConfidenceValue > prediction.apiConfidenceValue);
  assert.equal(prediction.confidence, `${prediction.confidenceValue.toFixed(1)}%`);
  assert.equal(prediction.predictionMode, 'pregame');
});

test('a high-impact unavailable starter materially lowers that team probability', () => {
  const healthy = predictGame(game(), 0, context({
    star: { id: 'star', name: 'Home Star', team: 'Home Team', league: 'NBA', role: 'primary scorer', impact: 9, availability: 100, status: 'available', starter: true, form: 50, updatedAt: new Date().toISOString() }
  }));
  const out = predictGame(game(), 0, context({
    star: { id: 'star', name: 'Home Star', team: 'Home Team', league: 'NBA', role: 'primary scorer', impact: 9, availability: 0, status: 'out', starter: true, form: 50, updatedAt: new Date().toISOString() }
  }));
  assert.ok(out.outcomeProbabilities.home < healthy.outcomeProbabilities.home - 5);
  assert.match(out.signals.join(' '), /Home Star/);
});

test('a matching manual player record overrides automatic injury status', () => {
  const automaticInjury = game({ autoPlayers: [{
    id: 'auto-star', name: 'Home Star', team: 'Home Team', league: 'NBA', role: 'primary scorer',
    impact: 9, availability: 0, status: 'out', starter: true, form: 50, autoGenerated: true, updatedAt: new Date().toISOString()
  }] });
  const automaticOnly = predictGame(automaticInjury, 0, context());
  const manualHealthy = predictGame(automaticInjury, 0, context({
    star: { id: 'star', name: 'Home Star', team: 'Home Team', league: 'NBA', role: 'primary scorer', impact: 9, availability: 100, status: 'available', starter: true, form: 50, updatedAt: new Date().toISOString() }
  }));
  assert.ok(manualHealthy.outcomeProbabilities.home > automaticOnly.outcomeProbabilities.home + 5);
  assert.ok(manualHealthy.localDataConfidenceValue > automaticOnly.localDataConfidenceValue);
});

test('soccer model includes an explicit draw probability', () => {
  const soccer = game({
    id: 'epl-example', league: 'Premier League', leagueKey: 'epl', sportGroup: 'Soccer', matchup: 'AWY @ HOM'
  });
  const prediction = predictGame(soccer, 0, context());
  assert.ok(prediction.outcomeProbabilities.draw > 10);
  const total = Object.values(prediction.outcomeProbabilities).reduce((sum, value) => sum + value, 0);
  assert.ok(Math.abs(total - 100) <= 0.2);
});

test('soccer rejects an incomplete two-way market that omits the draw', () => {
  const soccer = game({
    id: 'epl-incomplete-market', league: 'Premier League', leagueKey: 'epl', sportGroup: 'Soccer',
    odds: {
      bookmakerCount: 3,
      h2h: {
        bookmakerCount: 3, dispersion: 0.02,
        away: { fairProbability: 0.45, implied: 0.45, price: 120, bookmaker: 'Books' },
        home: { fairProbability: 0.55, implied: 0.55, price: -130, bookmaker: 'Books' },
        draw: null
      }
    }
  });
  const prediction = predictGame(soccer, 0, context());
  assert.ok(prediction.outcomeProbabilities.draw > 10);
  assert.equal(prediction.edgeValue, null);
  assert.match(prediction.marketSignal, /no odds dependency/i);
});

