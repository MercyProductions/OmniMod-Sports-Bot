import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash,randomUUID} from 'node:crypto';
const [root,role,mode]=process.argv.slice(2);
if(!root||!['baseline','challenger'].includes(role)||!['offline','live'].includes(mode))throw new Error('Invalid isolated worker invocation');
const state=join(root,'state',role);
if(resolve(process.env.OMNIMOD_SPORTS_DATA_DIR||'')!==resolve(state)||process.env.DISCORD_TOKEN||process.env.ODDS_API_KEY)throw new Error('Invalid isolated environment');
const source=join(root,role,'sports-bot','src');
const {config,dataDir}=await import(pathToFileURL(join(source,'config.js')));
if(resolve(dataDir)!==resolve(state)||config.discordToken||config.oddsApiKey||config.featureWarehouseEnabled||config.historicalReplayEnabled||config.localMlEnabled)throw new Error('Isolation configuration mismatch');
const {buildDailySlate}=await import(pathToFileURL(join(source,'sportsData.js')));
const startedAt=new Date().toISOString();
const slate=await buildDailySlate(new Date(),{guildId:'isolated-prospective',localOnly:mode==='offline',includeOdds:false,leagueKeys:['nba','nhl','nfl','mlb']});
const completedAt=new Date().toISOString();
const capture={schema:'sports-isolated-capture-v1',role,mode,startedAt,completedAt,slate,discordDelivered:false,liveOrders:false};
const bytes=JSON.stringify(capture)+'\n',captureHash=createHash('sha256').update(bytes).digest('hex');
await mkdir(join(root,'captures'),{recursive:true});
const filename=role+'-'+Date.now()+'-'+randomUUID()+'.json';
await writeFile(join(root,'captures',filename),bytes,{flag:'wx',mode:0o600});
console.log(JSON.stringify({role,mode,filename,captureHash,startedAt,completedAt,games:slate.games.length,
 pregameForecasts:slate.predictions.filter(row=>row.predictionMode==='pregame').length,diagnosticCount:slate.diagnostics?.length||0}));
