    pick: `${predictedWinner} ${predictedSide === 'draw' ? 'result' : 'to win'}${uncertainty.recommendationStatus === 'withheld' ? ' (high uncertainty)' : uncertainty.recommendationStatus === 'lean_only' ? ' (directional lean)' : ''}`,
    predictedWinner,
    predictedSide,
