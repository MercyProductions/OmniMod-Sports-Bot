import { config } from './config.js';
import { normalizeEntityName } from './intelligenceStore.js';
import { cachedFetchJson } from './providerCache.js';

const DAY_MS = 86_400_000;

function providerCall(result) {
  return result.cacheState === 'network' || result.cacheState === 'revalidated' ? 1 : 0;
}

function teamMatches(gameTeam, name, abbr = '') {
  const targets = [gameTeam?.name, gameTeam?.abbr].map(normalizeEntityName).filter(Boolean);
  return [name, abbr].map(normalizeEntityName).filter(Boolean).some((candidate) =>
    targets.some((target) => target === candidate || (target.length >= 5 && candidate.includes(target)) || (candidate.length >= 5 && target.includes(candidate)))
  );
}

function pushCorroboration(game, row) {
  game.sourceCorroboration ||= { providers: [], matches: [], conflicts: [] };
  if (!game.sourceCorroboration.providers.includes(row.provider)) game.sourceCorroboration.providers.push(row.provider);
  (row.conflict ? game.sourceCorroboration.conflicts : game.sourceCorroboration.matches).push(row);
}

function mergeOfficialPlayers(game, players) {
  const merged = new Map();
  for (const row of [...players, ...(game.autoPlayers || [])]) {
    const key = `${normalizeEntityName(row.team)}__${normalizeEntityName(row.name)}`;
    const existing = merged.get(key);
    merged.set(key, existing ? {
      ...existing,
      ...row,
      sources: [...new Set([...(existing.sources || [existing.source]), ...(row.sources || [row.source])].filter(Boolean))],
      officiallyCorroborated: true
    } : row);
  }
  game.autoPlayers = [...merged.values()];
}

function espnStatusComparable(statusKey) {
  if (statusKey === 'final') return 'final';
  if (statusKey === 'live') return 'live';
  return 'scheduled';
}

function mlbStatus(row) {
  const state = String(row?.status?.abstractGameState || row?.status?.detailedState || '').toLowerCase();
  if (/final|completed/.test(state)) return 'final';
  if (/live|in progress|warmup/.test(state)) return 'live';
  return 'scheduled';
}

async function corroborateMlb(games, dateKey) {
  const diagnostics = [];
  let externalCalls = 0;
  let matched = 0;
  let confirmedStarters = 0;
  const url = new URL('https://statsapi.mlb.com/api/v1/schedule');
  url.searchParams.set('sportId', '1');
  url.searchParams.set('date', dateKey);
  url.searchParams.set('hydrate', 'probablePitcher,team,venue');
  const result = await cachedFetchJson(url.toString(), {
    namespace: 'official-mlb-schedule',
    ttlMs: config.scoreboardCacheMinutes * 60_000,
    staleMs: config.scoreboardStaleHours * 60 * 60_000,
    timeoutMs: 12_000
  });
  externalCalls += providerCall(result);
  if (!result.ok || !result.json) return { diagnostics: [`MLB official source: unavailable (${result.error || 'no data'}).`], externalCalls, matched, confirmedStarters };
  const officialGames = result.json.dates?.flatMap((row) => row.games || []) || [];
  for (const game of games.filter((row) => row.leagueKey === 'mlb')) {
    const official = officialGames.find((row) =>
      teamMatches(game.away, row.teams?.away?.team?.name, row.teams?.away?.team?.abbreviation) &&
      teamMatches(game.home, row.teams?.home?.team?.name, row.teams?.home?.team?.abbreviation)
    );
    if (!official) continue;
    matched += 1;
    const officialStart = new Date(official.gameDate).getTime();
    const espnStart = new Date(game.startTime).getTime();
    const startDeltaMinutes = Number.isFinite(officialStart) && Number.isFinite(espnStart) ? Math.abs(officialStart - espnStart) / 60_000 : null;
    const statusConflict = mlbStatus(official) !== espnStatusComparable(game.statusKey);
    pushCorroboration(game, {
      provider: 'MLB StatsAPI',
      eventId: String(official.gamePk || ''),
      fetchedAt: result.fetchedAt,
      cacheState: result.cacheState,
      startDeltaMinutes,
      status: mlbStatus(official),
      conflict: statusConflict || (startDeltaMinutes !== null && startDeltaMinutes > 30)
    });
    const players = [];
    for (const side of ['away', 'home']) {
      const probable = official.teams?.[side]?.probablePitcher;
      if (!probable?.fullName) continue;
      confirmedStarters += 1;
      players.push({
        id: `official-mlb-${official.gamePk}-${probable.id}`,
        sourceAthleteId: String(probable.id || ''),
        name: probable.fullName,
        team: game[side].name,
        league: game.league,
        leagueKey: game.leagueKey,
        role: 'Starting Pitcher',
        impact: 6,
        availability: 100,
        status: 'probable starter on official MLB schedule',
        starter: true,
        form: 50,
        stats: {},
        source: 'MLB StatsAPI probable pitcher',
        sources: ['MLB StatsAPI probable pitcher'],
        autoGenerated: true,
        updatedAt: result.fetchedAt
      });
    }
    mergeOfficialPlayers(game, players);
  }
  diagnostics.push(`MLB official source: corroborated ${matched}/${games.filter((row) => row.leagueKey === 'mlb').length} game(s), ${confirmedStarters} probable starter(s), source=${result.cacheState}.`);
  return { diagnostics, externalCalls, matched, confirmedStarters };
}

function nhlStatus(row) {
  const state = String(row?.gameState || '').toUpperCase();
  if (['OFF', 'FINAL'].includes(state)) return 'final';
  if (['LIVE', 'CRIT'].includes(state)) return 'live';
  return 'scheduled';
}

async function corroborateNhl(games, dateKey) {
  let externalCalls = 0;
  let matched = 0;
  const url = `https://api-web.nhle.com/v1/score/${encodeURIComponent(dateKey)}`;
  const result = await cachedFetchJson(url, {
    namespace: 'official-nhl-score',
    ttlMs: config.scoreboardCacheMinutes * 60_000,
    staleMs: config.scoreboardStaleHours * 60 * 60_000,
    timeoutMs: 12_000
  });
  externalCalls += providerCall(result);
  if (!result.ok || !result.json) return { diagnostics: [`NHL official source: unavailable (${result.error || 'no data'}).`], externalCalls, matched, confirmedStarters: 0 };
  for (const game of games.filter((row) => row.leagueKey === 'nhl')) {
    const official = (result.json.games || []).find((row) =>
      teamMatches(game.away, row.awayTeam?.name?.default, row.awayTeam?.abbrev) &&
      teamMatches(game.home, row.homeTeam?.name?.default, row.homeTeam?.abbrev)
    );
    if (!official) continue;
    matched += 1;
    const officialStart = new Date(official.startTimeUTC).getTime();
    const espnStart = new Date(game.startTime).getTime();
    const startDeltaMinutes = Number.isFinite(officialStart) && Number.isFinite(espnStart) ? Math.abs(officialStart - espnStart) / 60_000 : null;
    const statusConflict = nhlStatus(official) !== espnStatusComparable(game.statusKey);
    pushCorroboration(game, {
      provider: 'NHL API', eventId: String(official.id || ''), fetchedAt: result.fetchedAt,
      cacheState: result.cacheState, startDeltaMinutes, status: nhlStatus(official),
      conflict: statusConflict || (startDeltaMinutes !== null && startDeltaMinutes > 30)
    });
  }
  return {
    diagnostics: [`NHL official source: corroborated ${matched}/${games.filter((row) => row.leagueKey === 'nhl').length} game(s), source=${result.cacheState}.`],
    externalCalls, matched, confirmedStarters: 0
  };
}

export async function corroborateOfficialSources(games, dateKey, options = {}) {
  if (options.localOnly || config.localOnly || !config.autoOfficialSources) {
    return { games, diagnostics: [`Official-source corroboration: skipped (${options.localOnly || config.localOnly ? 'LOCAL_ONLY=true' : 'AUTO_OFFICIAL_SOURCES=false'}).`], externalCalls: 0, matched: 0, confirmedStarters: 0 };
  }
  const tasks = [];
  if (games.some((game) => game.leagueKey === 'mlb')) tasks.push(corroborateMlb(games, dateKey));
  if (games.some((game) => game.leagueKey === 'nhl')) tasks.push(corroborateNhl(games, dateKey));
  const results = await Promise.all(tasks);
  return {
    games,
    diagnostics: results.flatMap((row) => row.diagnostics),
    externalCalls: results.reduce((total, row) => total + row.externalCalls, 0),
    matched: results.reduce((total, row) => total + row.matched, 0),
    confirmedStarters: results.reduce((total, row) => total + row.confirmedStarters, 0)
  };
}

export function officialSourceStaleWindowMs() {
  return Math.max(config.scoreboardStaleHours * 60 * 60_000, 2 * DAY_MS);
}

